-- Run this script once in Supabase SQL Editor.
-- The public browser client must use the anon key only.

create table if not exists public.guestbook (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(trim(name)) between 1 and 20),
    message text not null check (char_length(trim(message)) between 1 and 200),
    created_at timestamptz not null default now()
);

alter table public.guestbook enable row level security;

drop policy if exists "Anyone can read guestbook" on public.guestbook;
create policy "Anyone can read guestbook"
on public.guestbook
for select
to anon
using (true);

drop policy if exists "Anyone can add guestbook message" on public.guestbook;
create policy "Anyone can add guestbook message"
on public.guestbook
for insert
to anon
with check (
    char_length(trim(name)) between 1 and 20
    and char_length(trim(message)) between 1 and 200
);
